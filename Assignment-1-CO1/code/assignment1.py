from __future__ import annotations
from collections import deque
from dataclasses import dataclass
import csv, heapq, random, time, json, math
from pathlib import Path

OUT=Path(__file__).parent/"results"; OUT.mkdir(exist_ok=True)
@dataclass
class Result:
    path:list|None; generated:int; expanded:int; max_frontier:int; cost:float; seconds:float
def graph_line(n:int, seed:int=17):
    """Connected weighted chain plus deterministic short-cuts; nodes 0..n-1."""
    rng=random.Random(seed); g=[[] for _ in range(n)]
    for i in range(n-1):
        w=rng.randint(1,9); g[i].append((i+1,w)); g[i+1].append((i,w))
    # sparse shortcuts preserve connectedness and give alternative weighted routes
    for _ in range(max(1,n//20)):
        u=rng.randrange(n); v=min(n-1,u+rng.randint(2,40))
        if u!=v:
            w=rng.randint(1,12); g[u].append((v,w)); g[v].append((u,w))
    return g
def reconstruct(parent,goal):
    if goal not in parent:return None
    p=[]; x=goal
    while x is not None:p.append(x); x=parent[x]
    return p[::-1]
def bfs(g,s,t):
    st=time.perf_counter(); q=deque([s]); parent={s:None}; gen=1; exp=0; peak=1
    while q:
        u=q.popleft(); exp+=1
        if u==t:break
        for v,w in g[u]:
            if v not in parent:parent[v]=u; q.append(v); gen+=1
        peak=max(peak,len(q))
    p=reconstruct(parent,t); cost=sum(next(w for v,w in g[a] if v==b) for a,b in zip(p,p[1:])) if p else math.inf
    return Result(p,gen,exp,peak,cost,time.perf_counter()-st)
def ucs(g,s,t):
    st=time.perf_counter(); pq=[(0,s)]; dist={s:0}; parent={s:None}; gen=1; exp=0; peak=1
    while pq:
        d,u=heapq.heappop(pq)
        if d!=dist[u]:continue
        exp+=1
        if u==t:break
        for v,w in g[u]:
            nd=d+w
            if nd<dist.get(v,math.inf):
                dist[v]=nd; parent[v]=u; heapq.heappush(pq,(nd,v)); gen+=1
        peak=max(peak,len(pq))
    p=reconstruct(parent,t)
    return Result(p,gen,exp,peak,dist.get(t,math.inf),time.perf_counter()-st)
def recursive_dls(g,s,t,limit):
    """Recursive depth-limited DFS; path-set prevents cycles, depth limit prevents runaway recursion."""
    st=time.perf_counter(); path=[s]; onpath={s}; counts=[1,0,1]; found=[False]
    def visit(u,depth):
        counts[1]+=1
        if u==t:found[0]=True;return True
        if depth==limit:return False
        for v,w in g[u]:
            if v not in onpath:
                counts[0]+=1; path.append(v); onpath.add(v); counts[2]=max(counts[2],len(path))
                if visit(v,depth+1):return True
                path.pop();onpath.remove(v)
        return False
    try: ok=visit(s,0)
    except RecursionError: ok=False
    p=path.copy() if ok else None
    # DFS path cost follows actual edges
    cost=sum(next(w for v,w in g[a] if v==b) for a,b in zip(p,p[1:])) if p else math.inf
    return Result(p,counts[0],counts[1],counts[2],cost,time.perf_counter()-st)
def belief_experiment(k_values=(2,4,8)):
    rows=[]
    for k in k_values:
        # Belief state represented as a frozenset of candidate locations.
        # A distinguishing local sensor resolves the belief in one observation.
        rows.append({"k":k,"belief_states_without_sensor":2**k-1,
                     "worst_case_sensing_actions_without_sensor":k,
                     "belief_states_with_local_sensor":k+1,
                     "sensing_actions_with_local_sensor":1})
    return rows
def main():
    rows=[]
    for n in (1000,10000,100000,1000000):
        g=graph_line(n); s,t=0,n-1
        for name,fn in (("BFS",bfs),("UCS",ucs)):
            samples=[fn(g,s,t) for _ in range(5)]
            r=samples[-1]
            rows.append({"states":n,"algorithm":name,"generated":r.generated,"expanded":r.expanded,
                         "max_frontier":r.max_frontier,"depth":len(r.path)-1 if r.path else -1,
                         "path_cost":r.cost,"optimal":name=="UCS",
                         "mean_seconds":sum(x.seconds for x in samples)/len(samples)})
        # Recursive DFS deliberately capped: demonstrates recursion-stack limitation safely.
        limit=min(n-1,800)
        r=recursive_dls(g,s,t,limit)
        rows.append({"states":n,"algorithm":"recursive_DLS","generated":r.generated,"expanded":r.expanded,
                     "max_frontier":r.max_frontier,"depth":len(r.path)-1 if r.path else -1,
                     "path_cost":r.cost,"optimal":False,"mean_seconds":r.seconds,
                     "note":"depth-limited; recursion limit/limit may prevent reaching distant goal"})
        print(f"n={n}: "+", ".join(f"{x['algorithm']} exp={x['expanded']} generated={x['generated']} depth={x['depth']}" for x in rows[-3:]))
    with (OUT/"a1_search_metrics.csv").open("w",newline="") as f:
        w=csv.DictWriter(f,fieldnames=sorted({k for r in rows for k in r}));w.writeheader();w.writerows(rows)
    with (OUT/"a1_belief_metrics.csv").open("w",newline="") as f:
        w=csv.DictWriter(f,fieldnames=belief_experiment()[0].keys());w.writeheader();w.writerows(belief_experiment())
    print("Saved",OUT/"a1_search_metrics.csv","and",OUT/"a1_belief_metrics.csv")
if __name__=="__main__":main()
